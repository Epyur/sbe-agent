/** Подставляет динамические части в шаблон системного промпта. */
export function renderSystemPrompt(
  template: string,
  ctx: {
    getUserName: () => string;
    getEmail: () => string;
    getSources: () => SourceAvailability[];
  },
  tools: AgentTool[],
): string {
  const sources = ctx.getSources();
  const sourceList = sources.length > 0
    ? sources.map(s => `- ${s.name}${s.available ? (s.role ? ` (${s.role})` : '') : ' (нет доступа)'}`).join('\n')
    : '- локальная база задач (всегда доступна)';

  const toolLines = tools.map(t => JSON.stringify({
    name: t.schema.name,
    description: t.schema.description,
    input_schema: t.schema.input_schema,
  }));

  return template
    .split('{{ПОЛЬЗОВАТЕЛЬ}}').join(`${ctx.getUserName() || '—'} (${ctx.getEmail() || '—'})`)
    .split('{{ИСТОЧНИКИ}}').join(sourceList)
    .split('{{СХЕМА_КЭШЕЙ}}').join(cacheSchemaText())
    .split('{{ИНСТРУМЕНТЫ}}').join(toolLines.join('\n'));
}
